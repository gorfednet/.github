#!/usr/bin/env node
/**
 * The ranked plan (plan row 4.1): every open backlog entry across the fleet, one line each,
 * in the owner's priority order, pointing at `<repo>:<backlog file>#<id>`.
 *
 *   node scripts/plan-of-record.mjs --clones ~/Developer/gorfednet [--fetch] --out <file>
 *   node scripts/plan-of-record.mjs --out <file>            # reads each backlog through gh api
 *   node scripts/plan-of-record.mjs ... --check <file>      # exit 1 when <file> is out of date
 *
 * Inputs: docs/plan-ranking.json (hand-kept: tiers and repositories, no entry ids) and each
 * repository's backlog on its default branch. Nothing is typed by hand into the output, so
 * regenerating it is the only way to change it.
 *
 * The output names private repositories' entries, so it is written to a private repository
 * (gorfednet/ops docs/plan-ranked.md), never committed here: this repository is public, and
 * fleet-status keeps private entry ids out of it for the same reason.
 *
 * Fails closed: an unreadable backlog, or a fleet repository the ranking file does not place,
 * is an error, never a silent gap.
 */
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

import { isMain } from '../templates/verification-kit/lib/isMain.mjs'
import { repoList } from './fleet-status.mjs'

const CLOSED = new Set(['landed', 'declined'])
/** Bugs before suspicions before work already in review. ops says "open" for a confirmed item. */
const STATUS_ORDER = { 'confirmed-bug': 0, open: 0, suspected: 1, 'in-review': 2 }

export const short = (slug) => slug.split('/').pop()
const fileName = (path) => path.split('/').pop()

/** Today in Toronto, YYYY-MM-DD. */
export const torontoDay = (d = new Date()) => new Intl.DateTimeFormat('en-CA', { timeZone: 'America/Toronto' }).format(d)

/** "21 Nov 2026" */
const dayLabel = (iso) =>
  new Intl.DateTimeFormat('en-GB', { timeZone: 'UTC', day: 'numeric', month: 'short', year: 'numeric' }).format(new Date(`${iso}T00:00:00Z`))

/** Fleet repositories (fleet.json plus ship-bot, dormant ones left out) that the ranking file does not place. */
export function unranked(ranking, fleet, shipBotConfig) {
  const placed = new Set(ranking.tiers.flatMap((t) => t.repos.map((r) => r.slug)))
  return repoList(fleet, shipBotConfig).filter((s) => !placed.has(s))
}

/**
 * @param ranking docs/plan-ranking.json
 * @param backlogs Map slug -> parsed backlog ({entries}) or null when the repository keeps none
 * @param today YYYY-MM-DD
 */
export function rankEntries(ranking, backlogs, today) {
  const rows = []
  for (const tier of [...ranking.tiers].sort((a, b) => a.rank - b.rank)) {
    tier.repos.forEach((repo, repoIndex) => {
      const doc = backlogs.get(repo.slug)
      for (const e of doc?.entries ?? []) {
        if (!e || CLOSED.has(e.status) || e.id === 'example-entry-replace-me') continue
        rows.push({
          rank: tier.rank,
          tier: tier.name,
          repoIndex,
          pointer: `${short(repo.slug)}:${fileName(repo.backlog ?? 'docs/backlog.json')}#${e.id}`,
          title: e.title ?? '',
          status: e.status,
          owner: e.assignee === 'human',
          reviewBy: typeof e.reviewBy === 'string' ? e.reviewBy : null,
          lapsed: typeof e.reviewBy === 'string' && e.reviewBy < today,
        })
      }
    })
  }
  const order = (s) => STATUS_ORDER[s] ?? 3
  return rows.sort(
    (a, b) =>
      a.rank - b.rank ||
      order(a.status) - order(b.status) ||
      (a.reviewBy ?? '9999').localeCompare(b.reviewBy ?? '9999') ||
      a.repoIndex - b.repoIndex ||
      a.pointer.localeCompare(b.pointer),
  )
}

const cell = (s) => String(s).replace(/\r?\n/g, ' ')

function line(r, n) {
  const facts = [r.status, r.reviewBy ? `review by ${dayLabel(r.reviewBy)}${r.lapsed ? ' (lapsed)' : ''}` : 'no review date']
  if (r.owner) facts.push('owner')
  return `${n}. \`${r.pointer}\` ${cell(r.title)} · ${facts.join(' · ')}`
}

export function renderPlan(rows, today) {
  const lapsed = rows.filter((r) => r.lapsed).length
  const undated = rows.filter((r) => !r.reviewBy).length
  const owner = rows.filter((r) => r.owner)
  const out = [
    '<!-- Generated by gorfednet/.github scripts/plan-of-record.mjs from docs/plan-ranking.json and each repository\'s backlog. Do not edit by hand. -->',
    '# Ranked plan',
    '',
    `Generated ${dayLabel(today)}. ${rows.length} open entries, ${lapsed} lapsed, ${undated} with no review date, ${owner.length} owner-only.`,
    '',
    'Order: the owner\'s priority (9 November 2026), then confirmed bugs before suspicions before work in review, then the nearest review date.',
    '',
  ]
  if (owner.length) {
    out.push('## Owner-only', '')
    owner.forEach((r, i) => out.push(line(r, i + 1)))
    out.push('')
  }
  let n = 0
  for (const rank of [...new Set(rows.map((r) => r.rank))]) {
    const tierRows = rows.filter((r) => r.rank === rank)
    out.push(`## ${rank}. ${tierRows[0].tier}`, '')
    for (const r of tierRows) out.push(line(r, ++n))
    out.push('')
  }
  return out.join('\n')
}

function arg(name) {
  const at = process.argv.indexOf(name)
  return at !== -1 ? process.argv[at + 1] : null
}

export function repoReadable(slug, run = execFileSync) {
  try {
    run('gh', ['api', `repos/${slug}`, '--jq', '.full_name'], { stdio: ['ignore', 'pipe', 'pipe'] })
    return true
  } catch {
    return false
  }
}

function readBacklog(repo, clones, fetch) {
  const path = repo.backlog ?? 'docs/backlog.json'
  try {
    if (clones) {
      const dir = join(clones, repo.dir)
      if (fetch) execFileSync('git', ['-C', dir, 'fetch', '-q', 'origin'], { stdio: 'ignore' })
      return JSON.parse(execFileSync('git', ['-C', dir, 'show', `origin/HEAD:${path}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }))
    }
    return JSON.parse(execFileSync('gh', ['api', '-H', 'Accept: application/vnd.github.raw', `repos/${repo.slug}/contents/${path}`], { encoding: 'utf8', stdio: ['ignore', 'pipe', 'pipe'] }))
  } catch (cause) {
    const text = String(cause.stderr || cause.message)
    if (clones && /does not exist in|exists on disk, but not in/.test(text)) return null
    // GitHub answers 404 for a missing file, but also for a repository the token can't see or a
    // wrong slug. Only a readable repository turns a 404 into "keeps no backlog".
    if (!clones && /HTTP 404/.test(text) && repoReadable(repo.slug)) return null
    throw new Error(`${repo.slug}: could not read ${path}: ${text.trim().split('\n')[0]}`)
  }
}

if (isMain(import.meta.url)) {
  const read = (rel) => JSON.parse(readFileSync(new URL(rel, import.meta.url), 'utf8'))
  const ranking = read('../docs/plan-ranking.json')
  const missing = unranked(ranking, read('../fleet.json'), read('../ship-bot/config.example.json'))
  if (missing.length) {
    console.error(`plan-of-record: docs/plan-ranking.json does not place ${missing.join(', ')}`)
    process.exit(1)
  }
  const backlogs = new Map()
  const failures = []
  for (const repo of ranking.tiers.flatMap((t) => t.repos)) {
    try {
      backlogs.set(repo.slug, readBacklog(repo, arg('--clones'), process.argv.includes('--fetch')))
    } catch (e) {
      failures.push(e.message)
    }
  }
  if (failures.length) {
    console.error(`plan-of-record: ${failures.length} backlog(s) unreadable:\n  ${failures.join('\n  ')}`)
    process.exit(1)
  }
  const today = torontoDay()
  const md = renderPlan(rankEntries(ranking, backlogs, today), today)
  const check = arg('--check')
  if (check) {
    const strip = (s) => s.replace(/^Generated [^.]+\./m, '')
    if (strip(readFileSync(check, 'utf8')) !== strip(md)) {
      console.error(`plan-of-record: ${check} is out of date; regenerate it`)
      process.exit(1)
    }
    console.log(`plan-of-record: ${check} is current`)
  } else if (arg('--out')) {
    writeFileSync(arg('--out'), md)
    console.log(`plan-of-record: ${md.split('\n').filter((l) => /^\d+\. /.test(l)).length} lines -> ${arg('--out')}`)
  } else {
    process.stdout.write(md)
  }
}
